-- Compatibility migration for the existing Control de Stock Supabase project.
-- Its products/categories/customers/profiles and sales (shipments) already exist
-- with Spanish column names and integer IDs. This adds only purchasing tables.
begin;

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  contact_name text,
  phone text,
  email text,
  address text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchase_orders (
  id bigint generated by default as identity primary key,
  purchase_number bigint generated by default as identity unique,
  supplier_id bigint references public.suppliers(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  status text not null default 'draft' check (status in ('draft', 'received', 'cancelled')),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  notes text,
  ordered_at timestamptz not null default now(),
  received_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchase_order_items (
  id bigint generated by default as identity primary key,
  purchase_order_id bigint not null references public.purchase_orders(id) on delete cascade,
  product_id integer references public.products(id) on delete set null,
  product_name text not null,
  sku text,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_cost numeric(12,2) not null check (unit_cost >= 0),
  line_total numeric(12,2) generated always as (round(quantity * unit_cost, 2)) stored,
  created_at timestamptz not null default now()
);

create index if not exists purchase_orders_ordered_at_idx
  on public.purchase_orders(ordered_at desc);
create index if not exists purchase_order_items_order_idx
  on public.purchase_order_items(purchase_order_id);

alter table public.suppliers enable row level security;
alter table public.purchase_orders enable row level security;
alter table public.purchase_order_items enable row level security;

drop policy if exists "Ferreteria suppliers read" on public.suppliers;
create policy "Ferreteria suppliers read" on public.suppliers
  for select to public using (public.is_active_user());
drop policy if exists "Ferreteria suppliers admin write" on public.suppliers;
create policy "Ferreteria suppliers admin write" on public.suppliers
  for all to public using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Ferreteria purchases read" on public.purchase_orders;
create policy "Ferreteria purchases read" on public.purchase_orders
  for select to public using (public.is_active_user());
drop policy if exists "Ferreteria purchases admin write" on public.purchase_orders;
create policy "Ferreteria purchases admin write" on public.purchase_orders
  for all to public using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Ferreteria purchase items read" on public.purchase_order_items;
create policy "Ferreteria purchase items read" on public.purchase_order_items
  for select to public using (public.is_active_user());
drop policy if exists "Ferreteria purchase items admin write" on public.purchase_order_items;
create policy "Ferreteria purchase items admin write" on public.purchase_order_items
  for all to public using (public.is_admin()) with check (public.is_admin());

grant select, insert, update, delete on
  public.suppliers, public.purchase_orders, public.purchase_order_items to authenticated;
grant usage, select on sequence
  public.suppliers_id_seq,
  public.purchase_orders_id_seq,
  public.purchase_orders_purchase_number_seq,
  public.purchase_order_items_id_seq to authenticated;

commit;
