-- Ferreteria / Supabase (PostgreSQL)
-- Initial schema for a single store: catalog, inventory, customers, sales and purchasing.
-- Apply in the Supabase SQL Editor or as a migration. Assumes Supabase's auth schema exists.

begin;

create type public.app_role as enum ('admin', 'staff');
create type public.inventory_movement_type as enum (
  'opening', 'purchase', 'sale', 'return', 'adjustment', 'damage'
);
create type public.sale_status as enum ('draft', 'completed', 'cancelled');
create type public.purchase_status as enum ('draft', 'received', 'cancelled');

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- One profile per Supabase Auth user. New signups receive the least-privileged role.
create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role public.app_role not null default 'staff',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (user_id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.create_profile_for_new_user();

create or replace function public.current_app_role()
returns public.app_role
language sql
stable
security definer
set search_path = ''
as $$
  select p.role from public.profiles p where p.user_id = (select auth.uid())
$$;

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  contact_name text,
  phone text,
  email text,
  address text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  sku text not null unique,
  barcode text unique,
  name text not null,
  description text,
  category_id uuid references public.categories(id) on delete set null,
  supplier_id uuid references public.suppliers(id) on delete set null,
  unit text not null default 'unidad',
  cost_price numeric(12,2) not null default 0 check (cost_price >= 0),
  sale_price numeric(12,2) not null default 0 check (sale_price >= 0),
  stock_quantity numeric(12,3) not null default 0,
  minimum_stock numeric(12,3) not null default 0 check (minimum_stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  document_number text,
  phone text,
  email text,
  address text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index customers_document_number_unique
  on public.customers (document_number) where document_number is not null;

create table public.sales (
  id uuid primary key default gen_random_uuid(),
  sale_number bigint generated by default as identity unique,
  customer_id uuid references public.customers(id) on delete set null,
  created_by uuid references public.profiles(user_id) on delete set null,
  status public.sale_status not null default 'completed',
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  payment_method text,
  notes text,
  sold_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (discount <= subtotal)
);

create table public.sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null, -- snapshot preserves the receipt if the product is renamed/deleted
  sku text,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  cost_at_sale numeric(12,2) not null default 0 check (cost_at_sale >= 0),
  line_total numeric(12,2) generated always as (round(quantity * unit_price, 2)) stored,
  created_at timestamptz not null default now()
);

create table public.purchase_orders (
  id uuid primary key default gen_random_uuid(),
  purchase_number bigint generated by default as identity unique,
  supplier_id uuid references public.suppliers(id) on delete set null,
  created_by uuid references public.profiles(user_id) on delete set null,
  status public.purchase_status not null default 'draft',
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  notes text,
  ordered_at timestamptz not null default now(),
  received_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.purchase_order_items (
  id uuid primary key default gen_random_uuid(),
  purchase_order_id uuid not null references public.purchase_orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  sku text,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_cost numeric(12,2) not null check (unit_cost >= 0),
  line_total numeric(12,2) generated always as (round(quantity * unit_cost, 2)) stored,
  created_at timestamptz not null default now()
);

-- Inventory ledger; a positive quantity adds stock and a negative quantity removes it.
create table public.inventory_movements (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete restrict,
  movement_type public.inventory_movement_type not null,
  quantity_change numeric(12,3) not null check (quantity_change <> 0),
  unit_cost numeric(12,2) check (unit_cost is null or unit_cost >= 0),
  sale_id uuid references public.sales(id) on delete set null,
  purchase_order_id uuid references public.purchase_orders(id) on delete set null,
  created_by uuid references public.profiles(user_id) on delete set null,
  notes text,
  created_at timestamptz not null default now()
);

create index products_category_id_idx on public.products(category_id);
create index products_supplier_id_idx on public.products(supplier_id);
create index products_name_idx on public.products using gin (to_tsvector('simple', name));
