create index sales_customer_id_idx on public.sales(customer_id);
create index sale_items_sale_id_idx on public.sale_items(sale_id);
create index sale_items_product_id_idx on public.sale_items(product_id);
create index purchase_orders_ordered_at_idx on public.purchase_orders(ordered_at desc);
create index purchase_order_items_order_idx on public.purchase_order_items(purchase_order_id);
create index inventory_movements_product_date_idx on public.inventory_movements(product_id, created_at desc);

create trigger categories_set_updated_at before update on public.categories
