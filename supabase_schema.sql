create policy "Users can read own profile; admins can read all"
  on public.profiles for select to authenticated
  using (user_id = (select auth.uid()) or (select public.current_app_role()) = 'admin');
-- No client insert/update policy on profiles: role changes should be made by a trusted admin.

create policy "Staff can read categories" on public.categories for select to authenticated using (true);
create policy "Admins manage categories" on public.categories for all to authenticated
  using ((select public.current_app_role()) = 'admin')
  with check ((select public.current_app_role()) = 'admin');

